"""
notices.py
----------
Fills in takedown-notice templates from a protected image's record, one
specific match (the URL you're reporting), your profile (Settings), and
a Case (see models/db.py). Template-filling from data Ward already has --
free, same as the original single-purpose dmca.py this module replaces.

THREE TEMPLATES, THREE DIFFERENT LEGAL BASES
    "copyright" -- the original DMCA notice. You're the copyright owner
        reporting an unauthorized copy.
    "ncii"      -- non-consensual intimate imagery. Different legal basis
        (privacy/personal-rights law, not copyright), different urgency,
        and platforms generally have a *faster*, dedicated reporting path
        for this than general copyright forms. This template points at
        the real, current specialized resources below rather than
        pretending a copyright notice is the right tool for this.
    "generic"   -- anything else (impersonation, a platform policy
        violation that isn't copyright or NCII). A plainer template that
        still gives the platform what any report needs: what the content
        is, where it is, why it violates policy, who's reporting it.

REAL RESOURCES, NOT INVENTED ONES
    StopNCII.org (hash-matching takedown for adults) and NCMEC's
    "Take It Down" (takeitdown.ncmec.org, for content involving anyone
    who was under 18 when the image/video was taken) are the actual
    current specialized services for this -- not being made up here.
    Both work by hashing the file on your own device and only sending
    the hash, not the image itself. Ward doesn't integrate with either
    API (that's real, separate integration work); it just prepares your
    own report and points you at them, exactly like the get-your-own-
    cert note in provenance.py is honest about what's still a manual
    step.

    Also real and worth citing in the notice itself: the U.S. TAKE IT
    DOWN Act (Pub. L. 119-12, effective May 2025) requires covered
    platforms to remove NCII within 48 hours of a valid request from
    the person depicted -- the template below cites it for U.S.
    platforms; it obviously doesn't apply to platforms outside U.S.
    jurisdiction, so treat that line as something to remove/adapt for
    non-U.S. services.

IMPORTANT: every template here is a starting point, not legal advice.
Ward is not a lawyer, doesn't know your jurisdiction, and doesn't verify
correctness for the specific platform you send it to. Review before
sending -- same caveat the original dmca.py had, now repeated for all
three templates instead of just one.
"""
from __future__ import annotations

from datetime import datetime, timezone

COPYRIGHT_TEMPLATE = """\
DMCA TAKEDOWN NOTICE

Date: {date}

To: The designated DMCA agent for {platform}

I am submitting this notice under Section 512(c) of the U.S. Digital
Millennium Copyright Act (or the equivalent notice-and-takedown
provision that applies in your jurisdiction / the platform's policy)
to report copyright infringement of my original work.

1. IDENTIFICATION OF THE COPYRIGHTED WORK
   Original work: {original_filename}
   Ward tracking ID: {tracking_id}
   (This ID is embedded as a machine-verifiable digital watermark in my
   original file, independent of any visible signature or metadata, and
   can be re-checked at any time against the file in question.)
{portfolio_line}
2. IDENTIFICATION OF THE INFRINGING MATERIAL
   URL: {infringing_url}
{infringing_source_line}   Found via reverse-image search on {found_at}.

3. STATEMENT OF GOOD FAITH BELIEF
   I have a good-faith belief that the use of the copyrighted material
   described above is not authorized by the copyright owner, its agent,
   or the law.

4. STATEMENT OF ACCURACY
   The information in this notice is accurate, and, under penalty of
   perjury, I am the owner, or authorized to act on behalf of the
   owner, of the exclusive copyright that is allegedly infringed.

5. CONTACT & SIGNATURE
   {reporter_name}
{contact_line}
{address_line}

   Signature: _______________________  Date: {date}

--
Generated by Ward. This is a template, not legal advice -- review it
before sending, and confirm the correct DMCA agent / reporting channel
for the specific platform hosting the infringing content.
"""

NCII_TEMPLATE = """\
PRIVACY / NON-CONSENSUAL IMAGERY REPORT

Date: {date}

To: The trust & safety / content-reporting team for {platform}

I am reporting content that depicts me without my consent, in violation
of {platform}'s policies and applicable privacy law. This is a personal
-rights matter, not a copyright claim -- please route it to your
non-consensual intimate imagery (NCII) or personal-content review
process rather than a general copyright queue.

1. THE CONTENT
   URL: {infringing_url}
{infringing_source_line}   Found via reverse-image search on {found_at}.
   Ward tracking ID (if this is a piece I registered with Ward beforehand): {tracking_id}

2. WHY THIS VIOLATES POLICY
   This content depicts me and was shared/posted without my consent.
   {platform}'s policy prohibits non-consensual intimate imagery and/or
   content depicting real people without consent (see {platform}'s own
   community guidelines for the exact clause).

3. REQUEST
   I am requesting immediate removal of this content and any known
   re-uploads or duplicates.{take_it_down_act_line}

4. CONTACT
   {reporter_name}
{contact_line}

--
ALSO CONSIDER, IN PARALLEL -- these are real, current, dedicated
services for exactly this situation, separate from any single
platform's own report form:
  - StopNCII.org -- lets you create a secure digital fingerprint (hash)
    of the image without uploading the image itself, which participating
    platforms then use to proactively detect and remove matches. For
    adults.
  - NCMEC's "Take It Down" (takeitdown.ncmec.org) -- the equivalent
    service for content involving anyone who was under 18 when the
    image/video was taken.
Both work independently of whatever you send {platform} directly, and
neither requires you to send the image itself to a stranger to use.

Generated by Ward. This is a template, not legal advice -- review it
before sending. If you are in immediate danger, contact local emergency
services or law enforcement directly; this template is for content
removal, not personal safety intervention.
"""

GENERIC_TEMPLATE = """\
CONTENT POLICY VIOLATION REPORT

Date: {date}

To: The content-review team for {platform}

I am reporting content that I believe violates {platform}'s policies.

1. THE CONTENT
   URL: {infringing_url}
{infringing_source_line}   Found via reverse-image search on {found_at}.
   Ward tracking ID (if this is a piece I registered with Ward beforehand): {tracking_id}

2. NATURE OF THE VIOLATION
   {violation_description}

3. REQUEST
   I am requesting review and removal of this content.

4. CONTACT
   {reporter_name}
{contact_line}

--
Generated by Ward. This is a template, not legal advice -- review it
before sending, and confirm the correct reporting channel for the
specific platform hosting this content.
"""

VALID_CASE_TYPES = ("copyright", "ncii", "generic")


def build_notice(
    *,
    case_type: str,
    original_filename: str = "",
    tracking_id: str = "",
    infringing_url: str,
    infringing_source: str = "",
    found_at: str = "",
    reporter_name: str = "",
    contact_email: str = "",
    portfolio_url: str = "",
    mailing_address: str = "",
    platform: str = "",
    violation_description: str = "",
) -> str:
    """Build a notice for `case_type` (see VALID_CASE_TYPES). Shared
    field-formatting logic across all three templates; each template
    only uses the placeholders relevant to it."""
    if case_type not in VALID_CASE_TYPES:
        raise ValueError(f"Unknown case_type '{case_type}'. Must be one of {VALID_CASE_TYPES}.")

    platform_name = platform.strip() if platform and platform.strip() else "the hosting platform"
    portfolio_line = f"   Originally published at: {portfolio_url}\n" if portfolio_url else ""
    infringing_source_line = f"   Source / platform: {infringing_source}\n" if infringing_source else ""
    contact_line = f"   Email: {contact_email}" if contact_email else "   Email: [ADD YOUR EMAIL]"
    address_line = mailing_address.strip() if mailing_address and mailing_address.strip() else (
        "   [Mailing address -- some platforms require one; add under Settings if needed]"
    )
    common = dict(
        date=datetime.now(timezone.utc).strftime("%Y-%m-%d"),
        platform=platform_name,
        original_filename=original_filename or "[untitled]",
        tracking_id=tracking_id or "[none]",
        portfolio_line=portfolio_line,
        infringing_url=infringing_url,
        infringing_source_line=infringing_source_line,
        found_at=found_at or "[date not recorded]",
        reporter_name=reporter_name or "[YOUR NAME -- add under Settings]",
        contact_line=contact_line,
        address_line=address_line,
        violation_description=violation_description or "[describe the specific policy this content violates]",
    )

    if case_type == "copyright":
        return COPYRIGHT_TEMPLATE.format(**common)
    if case_type == "ncii":
        # Real, current federal law -- see module docstring. Cited as a
        # separate optional line rather than baked into the fixed prose
        # above, since it only applies where the platform is subject to
        # U.S. jurisdiction; said plainly rather than assumed.
        common["take_it_down_act_line"] = (
            "\n   If this platform is subject to U.S. law: the federal TAKE IT DOWN Act "
            "(Pub. L. 119-12, effective May 2025) requires covered platforms to remove "
            "non-consensual intimate imagery within 48 hours of a valid request from the "
            "person depicted."
        )
        return NCII_TEMPLATE.format(**common)
    return GENERIC_TEMPLATE.format(**common)
